const modal = document.getElementById("modal");
const modalTitle = document.getElementById("mt");
const modalBody = document.getElementById("mb");
const modalNumber = document.getElementById("mn");
const modalClose = document.getElementById("close");


function openModal(item) {

  if (!modal) return;

  modalNumber.textContent = `مطلب ${item[0]}`;
  modalTitle.textContent = item[1];
  modalBody.innerHTML = item[3];

  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");

  document.body.style.overflow = "hidden";
}


function closeModal() {

  if (!modal) return;

  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");

  document.body.style.overflow = "";
}


/* =========================================================
   6. کلیک روی «مشاهده مطلب»
   ========================================================= */

document.addEventListener("click", function (event) {

  const button = event.target.closest(".read");

  if (!button) return;

  const source = button.dataset.source;
  const index = Number(button.dataset.index);

  const list =
    source === "warehousePosts"
      ? W
      : E;

  const item = list[index];

  if (!item) return;

  openModal(item);

});


/* =========================================================
   7. بستن Modal
   ========================================================= */

if (modalClose) {

  modalClose.addEventListener("click", closeModal);

}


if (modal) {

  modal.addEventListener("click", function (event) {

    if (event.target === modal) {
      closeModal();
    }

  });

}


/* =========================================================
   8. بستن با Escape
   ========================================================= */

document.addEventListener("keydown", function (event) {

  if (event.key === "Escape") {
    closeModal();
  }

});


