function drawPosts(items, containerId) {

  const container = document.getElementById(containerId);

  if (!container) return;

  container.innerHTML = items.map((item, index) => {

    return `
      <article class="post-card">

        <div class="post-number">
          ${item[0]}
        </div>

        <div class="post-content">

          <span class="post-label">
            ${containerId === "warehousePosts"
              ? "WAREHOUSE"
              : "MY EXPERIENCE"}
          </span>

          <h3>
            ${item[1]}
          </h3>

          <p>
            ${item[2]}
          </p>

          <button
            type="button"
            class="read"
            data-source="${containerId}"
            data-index="${index}"
          >
            مشاهده مطلب
            <span>←</span>
          </button>

        </div>

      </article>
    `;

  }).join("");

}


