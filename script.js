function draw(posts, elementId) {

  const container = document.getElementById(elementId);

  if (!container) {
    console.error("Element not found:", elementId);
    return;
  }

  container.innerHTML = posts.map((post, index) => {

    return `
      <article class="post">

        <small>مطلب ${post[0]}</small>

        <h3>${post[1]}</h3>

        <p>${post[2]}</p>

        <button
          class="read"
          type="button"
          data-source="${elementId}"
          data-index="${index}">
          مشاهده مطلب ←
        </button>

      </article>
    `;

  }).join("");
}


